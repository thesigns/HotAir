# Builds every model in tools/blender/models.py and writes the game's assets.
#
#   "E:\Programy\Blender Foundation\Blender 5.2\blender.exe" --background --factory-startup ^
#       --python tools/blender/build.py -- [preview-dir]
#
# Writes assets/models/models.glb, assets/models/models.blend and js/models/dims.js; with a preview
# directory also renders contact sheets of the models there (EEVEE).

import bpy
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
bpy.ops.wm.read_factory_settings(use_empty=True)
import models  # noqa: E402  (after the scene is reset: the module makes materials)
from mathutils import Vector  # noqa: E402

OUT = os.path.join(models.ROOT, 'assets', 'models')
os.makedirs(OUT, exist_ok=True)

objs, dims = [], {}
for fn in models.MODELS:
    m = fn()
    if m.dims:
        dims[m.name] = m.dims
    objs.append(m.finish())
    print(f'{m.name:22s} {len(objs[-1].data.polygons):5d} faces')

# the buildings' footprints and heights, for the generators and the collisions (they don't load the models)
with open(os.path.join(models.ROOT, 'js', 'models', 'dims.js'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/blender/build.py – the models\' sizes (metres): don\'t edit by hand.\n')
    f.write('export const DIMS = ' + json.dumps(dims, indent=2, sort_keys=True).replace('"', "'") + ';\n')

bpy.ops.export_scene.gltf(
    filepath=os.path.join(OUT, 'models.glb'), export_format='GLB', export_apply=True, export_yup=True,
    export_extras=False, export_normals=False, export_texcoords=False, export_materials='EXPORT',
)
bpy.ops.wm.save_as_mainfile(filepath=os.path.join(OUT, 'models.blend'), compress=True)


# ---------------------------------------------------------------- previews
def preview(prefixes, name, spacing=0.35):
    group = [o for o in objs if o.name.startswith(prefixes)]
    if not group:
        return
    scene = bpy.context.scene
    for o in objs:
        o.hide_render = o not in group
    # lay them out in a row, each by its size
    x = 0.0
    saved = {o: o.location.copy() for o in group}
    for o in group:
        xs = [c[0] for c in o.bound_box]
        w = max(xs) - min(xs)
        o.location.x = x - min(xs)
        x += w + max(2.0, w * spacing)
    bpy.context.view_layer.update()
    pts = [o.matrix_world @ Vector(c) for o in group for c in o.bound_box]
    lo = Vector((min(p.x for p in pts), min(p.y for p in pts), max(0, min(p.z for p in pts))))
    hi = Vector((max(p.x for p in pts), max(p.y for p in pts), max(p.z for p in pts)))
    centre = (lo + hi) / 2
    # an orthographic camera from the front, a little to the side and above
    cam = bpy.data.objects.new('cam', bpy.data.cameras.new('cam'))
    scene.collection.objects.link(cam)
    cam.data.type = 'ORTHO'
    d = Vector((-0.3, -1.0, 0.5)).normalized()
    cam.location = centre + d * 400
    cam.rotation_euler = (-d).to_track_quat('-Z', 'Y').to_euler()
    cam.data.clip_end = 2000
    aspect = scene.render.resolution_x / scene.render.resolution_y
    cam.data.ortho_scale = max((hi.x - lo.x) * 1.08, (hi.z - lo.z) * 1.25 * aspect, 4)
    scene.camera = cam
    scene.render.filepath = os.path.join(PREVIEW_DIR, name + '.png')
    bpy.ops.render.render(write_still=True)
    bpy.data.objects.remove(cam)
    for o, loc in saved.items():
        o.location = loc
    for o in objs:
        o.hide_render = False


PREVIEW_DIR = models.PREVIEW
if PREVIEW_DIR:
    scene = bpy.context.scene
    scene.render.engine = 'BLENDER_EEVEE'
    scene.render.resolution_x, scene.render.resolution_y = 1280, 720
    world = bpy.data.worlds.new('sky')
    world.color = (0.55, 0.65, 0.78)
    scene.world = world
    sun = bpy.data.objects.new('sun', bpy.data.lights.new('sun', 'SUN'))
    sun.data.energy = 4.0
    sun.rotation_euler = (math.radians(50), 0, math.radians(35))
    scene.collection.objects.link(sun)
    ground = bpy.data.meshes.new('ground')
    ground.from_pydata([(-500, -500, 0), (500, -500, 0), (500, 500, 0), (-500, 500, 0)], [], [(0, 1, 2, 3)])
    g = bpy.data.objects.new('ground', ground)
    gm = bpy.data.materials.new('ground')
    gm.diffuse_color = (0.25, 0.4, 0.15, 1)
    gm.use_nodes = True
    gm.node_tree.nodes.get('Principled BSDF').inputs['Base Color'].default_value = (0.2, 0.33, 0.12, 1)
    ground.materials.append(gm)
    scene.collection.objects.link(g)
    for prefixes, name in models.PREVIEWS:
        preview(prefixes, name)
